"""LLM-judge calibration (B4) and the blind pairwise human panel.

1) prepare:  python -m evals.runners.judge_calibration prepare
   writes evals/human/judge_labels.csv (30 proposals, judge scores hidden) and evals/human/pairwise.csv
   (anonymised V0-vs-shipped pairs, randomised A/B order; key in evals/human/pairwise_key.json).
2) a HUMAN fills `human_overall` (1-5) in judge_labels.csv and classmates fill `preferred` (A/B/tie) in pairwise.csv.
3) score:    python -m evals.runners.judge_calibration score
   -> evals/results/judge_calibration.json (Cohen's kappa, quadratic-weighted kappa, exact/±1 agreement) and
      evals/results/human_pairwise.json (win rate with a sign test).
No labels are ever generated by the AI.
"""

from __future__ import annotations

import csv
import json
import random
import sys

from common.settings import ROOT
from evals.harness import write

HUMAN = ROOT / "evals" / "human"
RES = ROOT / "evals" / "results"


def _rows() -> list[dict]:
    rows = []
    for f in ("gigsim_outcomes.json", "gigsim_outcomes_v4.json"):
        p = RES / f
        if p.exists():
            rows += [r for r in json.loads(p.read_text(encoding="utf-8"))["rows"] if r.get("text") and r.get("judge")]
    return rows


def prepare() -> None:
    HUMAN.mkdir(parents=True, exist_ok=True)
    rows = _rows()
    rng = random.Random(7)
    sample = rng.sample(rows, min(30, len(rows)))
    with (HUMAN / "judge_labels.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["item_id", "job_id", "proposal", "human_overall (1-5)", "notes"])
        for i, r in enumerate(sample):
            w.writerow([f"J{i:02d}", r["job_id"], r["text"], "", ""])
    (HUMAN / "judge_labels_key.json").write_text(json.dumps({f"J{i:02d}": {"variant": r["variant"], "job_id": r["job_id"],
                                                                           "judge": r["judge"]} for i, r in enumerate(sample)},
                                                            indent=1), encoding="utf-8")
    by_job: dict[str, dict] = {}
    for r in rows:
        by_job.setdefault(r["job_id"], {})[r["variant"]] = r
    pairs = [(j, v["v0_naive"], v["v4_outcome"]) for j, v in by_job.items() if "v0_naive" in v and "v4_outcome" in v]
    key = {}
    with (HUMAN / "pairwise.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["pair_id", "job_id", "proposal_A", "proposal_B", "preferred (A/B/tie)", "rater"])
        for i, (j, a, b) in enumerate(pairs):
            flip = rng.random() < 0.5
            A, B = (b, a) if flip else (a, b)
            key[f"P{i:02d}"] = {"A": A["variant"], "B": B["variant"]}
            w.writerow([f"P{i:02d}", j, A["text"], B["text"], "", ""])
    (HUMAN / "pairwise_key.json").write_text(json.dumps(key, indent=1), encoding="utf-8")
    print(f"wrote {len(sample)} judge items and {len(pairs)} pairs to {HUMAN}")


def _kappa(a: list[int], b: list[int], weighted: bool) -> float:
    cats = [1, 2, 3, 4, 5]
    n = len(a)
    obs = [[0] * 5 for _ in cats]
    for x, y in zip(a, b, strict=True):
        obs[x - 1][y - 1] += 1
    pa = [sum(obs[i]) / n for i in range(5)]
    pb = [sum(obs[i][j] for i in range(5)) / n for j in range(5)]
    w = [[((i - j) ** 2) / 16 if weighted else float(i != j) for j in range(5)] for i in range(5)]
    o = sum(w[i][j] * obs[i][j] / n for i in range(5) for j in range(5))
    e = sum(w[i][j] * pa[i] * pb[j] for i in range(5) for j in range(5))
    return round(1 - o / e, 3) if e else 1.0


def score() -> None:
    key = json.loads((HUMAN / "judge_labels_key.json").read_text(encoding="utf-8"))
    human, judge, items = [], [], []
    with (HUMAN / "judge_labels.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            v = (r.get("human_overall (1-5)") or "").strip()
            if v.isdigit():
                human.append(int(v))
                judge.append(int(key[r["item_id"]]["judge"]["overall"]))
                items.append({"item_id": r["item_id"], "human": int(v), "judge": judge[-1], "notes": r.get("notes", "")})
    if not human:
        print("no human labels yet — fill evals/human/judge_labels.csv first")
        return
    write("judge_calibration", {"n": len(human), "cohen_kappa": _kappa(human, judge, False),
                                "quadratic_weighted_kappa": _kappa(human, judge, True),
                                "exact_agreement": round(sum(h == j for h, j in zip(human, judge, strict=True)) / len(human), 3),
                                "within_one": round(sum(abs(h - j) <= 1 for h, j in zip(human, judge, strict=True)) / len(human), 3),
                                "disagreements": [i for i in items if abs(i["human"] - i["judge"]) >= 2], "items": items})
    pk = HUMAN / "pairwise.csv"
    if pk.exists():
        pkey = json.loads((HUMAN / "pairwise_key.json").read_text(encoding="utf-8"))
        wins: dict[str, int] = {}
        n = 0
        with pk.open(encoding="utf-8") as f:
            for r in csv.DictReader(f):
                pref = (r.get("preferred (A/B/tie)") or "").strip().upper()
                if pref in ("A", "B"):
                    wins[pkey[r["pair_id"]][pref]] = wins.get(pkey[r["pair_id"]][pref], 0) + 1
                    n += 1
        if n:
            from scipy.stats import binomtest

            k = wins.get("v4_outcome", 0)
            write("human_pairwise", {"n_decisive": n, "wins": wins, "shipped_win_rate": round(k / n, 3),
                                     "sign_test_p": round(binomtest(k, n, 0.5).pvalue, 4)})
    print("scored")


if __name__ == "__main__":
    {"prepare": prepare, "score": score}[sys.argv[1] if len(sys.argv) > 1 else "prepare"]()
