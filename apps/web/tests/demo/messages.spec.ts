// Demo step: a client reply handled (suggested reply waiting for approval, then approved).
import { expect, test } from '@playwright/test'

test('client reply handled', async ({ page }) => {
  test.setTimeout(10 * 60_000)
  await page.goto('/login')
  await page.getByLabel('Email').fill(process.env.DEMO_EMAIL ?? '')
  await page.getByLabel('Password').fill(process.env.DEMO_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Job inbox' })).toBeVisible()
  await page.goto('/messages')
  const first = page.getByRole('list', { name: 'Threads' }).getByRole('button').first()
  await first.waitFor({ timeout: 120_000 })
  await first.click()
  await expect(page.getByText('Suggested reply', { exact: false }).first()).toBeVisible({ timeout: 120_000 })
  await page.waitForTimeout(800)
  await page.screenshot({ path: '../../docs/demo/frames/09-reply-suggested.png' })
  await page.getByTestId('approve').click()
  await page.waitForTimeout(20_000)
  await page.reload()
  await first.waitFor({ timeout: 60_000 })
  await first.click()
  await page.waitForTimeout(3000)
  await page.screenshot({ path: '../../docs/demo/frames/10-reply-sent.png' })
  await page.goto('/runs')
  await page.getByRole('link', { name: /run-/ }).first().click()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: '../../docs/demo/frames/11-run-viewer.png' })
  await page.goto('/analytics')
  await page.waitForTimeout(1500)
  await page.screenshot({ path: '../../docs/demo/frames/12-analytics.png' })
})
