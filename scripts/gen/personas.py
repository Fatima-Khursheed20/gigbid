def project_dict(p: tuple, persona: str) -> dict:
    keys = ["id", "title", "repo", "industry", "client", "date", "explicit", "implied", "problem", "approach",
            "result", "readme_style"]
    d = dict(zip(keys, p, strict=True))
    d["persona"] = persona
    d["skills"] = sorted(set(d["explicit"]) | set(d["implied"]))
    return d


def all_projects(persona: str) -> list[dict]:
    return [project_dict(p, persona) for p in PERSONAS[persona]["projects"]]


def persona_skills(persona: str) -> set[str]:
    s: set[str] = set()
    for p in all_projects(persona):
        s |= set(p["skills"])
    return s
